def explain_th(n,system,rep):
    if system=='roman':return f'{rep["text"]} = {n} ใช้การบวกตามลำดับค่า และลบได้เฉพาะคู่ IV, IX, XL, XC, CD, CM'
    if system=='thai':return f'{rep["text"]} = {n} เปลี่ยนรูปตัวเลขโดยคงค่าประจำหลักฐานสิบไว้'
